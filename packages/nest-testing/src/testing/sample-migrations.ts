import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

/**
 * Constant ORGANIZATION_PREDICATE
 *
 * @description
 * Predicate of the row-level security policy of `@cadenway/nest-common/database`, as its README
 * documents it.
 *
 * @type {string}
 */
export const ORGANIZATION_PREDICATE: string =
  "organization_id = nullif(current_setting('app.organization_id', true), '')::uuid " +
  "or current_setting('app.system_access', true) = 'on'";

/**
 * Constant TASKS_MIGRATION
 *
 * @description
 * Statements of a service migration that creates one tenant-owned table the way the database
 * conventions ask: id generated by PostgreSQL, row-level security enabled and forced, the
 * organization policy.
 *
 * @type {readonly string[]}
 */
export const TASKS_MIGRATION: readonly string[] = [
  `create table "tasks" (
     "id" uuid primary key default uuidv7(),
     "organization_id" uuid not null,
     "display_key" text not null,
     "title" text not null,
     "status" text not null
   )`,
  'alter table "tasks" enable row level security',
  'alter table "tasks" force row level security',
  `create policy "organization_isolation" on "tasks" as permissive for all
     using (${ORGANIZATION_PREDICATE}) with check (${ORGANIZATION_PREDICATE})`,
];

/**
 * Interface SampleMigrations
 *
 * @description
 * A Drizzle migrations folder written in a temporary directory.
 */
export interface SampleMigrations {
  // #region Properties
  /**
   * Property folder
   *
   * @description
   * Absolute path of the folder, holding `meta/_journal.json` and one SQL file.
   *
   * @type {string}
   * @readonly
   */
  readonly folder: string;
  // #endregion

  // #region Methods
  /**
   * Method remove
   *
   * @description
   * Deletes the temporary directory.
   *
   * @returns {void}
   */
  remove(): void;
  // #endregion
}

/**
 * Function writeSampleMigrations
 *
 * @description
 * Writes a migrations folder in the layout drizzle-kit generates, with one migration made of
 * the given statements, so a spec applies it with the real Drizzle migrator.
 *
 * @param {readonly string[]} statements - Statements of the migration. Defaults to `TASKS_MIGRATION`.
 * @returns {SampleMigrations} The folder and how to delete it.
 */
export function writeSampleMigrations(
  statements: readonly string[] = TASKS_MIGRATION,
): SampleMigrations {
  const root: string = mkdtempSync(join(tmpdir(), 'cadenway-nest-testing-'));
  const folder: string = join(root, 'migrations');
  mkdirSync(join(folder, 'meta'), { recursive: true });
  writeFileSync(
    join(folder, 'meta', '_journal.json'),
    JSON.stringify({
      version: '7',
      dialect: 'postgresql',
      entries: [
        { idx: 0, version: '7', when: 1_731_500_000_000, tag: '0000_tasks', breakpoints: true },
      ],
    }),
  );
  writeFileSync(join(folder, '0000_tasks.sql'), statements.join(';\n--> statement-breakpoint\n'));
  return {
    folder,
    remove: (): void => {
      rmSync(root, { recursive: true, force: true });
    },
  };
}
